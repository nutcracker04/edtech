class ExtractedQuestion(BaseModel):
    """Legacy extracted question model for backward compatibility."""
    question_number: int
    question_text: str
    options: List[Dict[str, str]]  # [{"id": "A", "text": "..."}, ...]
    confidence: float  # OCR confidence score
    subject: Optional[str] = None
    topic: Optional[str] = None

    @classmethod
    def from_db_raw_question(cls, db_raw_question: DBRawQuestion, confidence: float = 0.9) -> 'ExtractedQuestion':
        """
        Convert database RawQuestion to legacy ExtractedQuestion format.
        
        Args:
            db_raw_question: Database raw question model
            confidence: OCR confidence score (default 0.9)
        
        Returns:
            Legacy ExtractedQuestion instance
        """
        # Convert options list to legacy format with IDs
        options = []
        for idx, option_text in enumerate(db_raw_question.options):
            options.append({
                "id": chr(65 + idx),  # A, B, C, D, ...
                "text": option_text
            })
        
        # Parse question number to int (handle formats like "1", "2a", "Q5")
        try:
            question_num = int(''.join(filter(str.isdigit, db_raw_question.question_number)))
        except (ValueError, TypeError):
            question_num = 0
        
        return cls(
            question_number=question_num,
            question_text=db_raw_question.question_text,
            options=options,
            confidence=confidence,
            subject=db_raw_question.chapter_context,  # Using chapter_context as subject
            topic=db_raw_question.topic_context
        )

    def to_db_raw_question(self, job_id: UUID, page_number: Optional[int] = None) -> DBRawQuestion:
        """
        Convert legacy ExtractedQuestion to database RawQuestion format.
        
        Args:
            job_id: Extraction job ID
            page_number: Optional page number
        
        Returns:
            Database RawQuestion instance
        """
        # Convert options to simple list of strings
        options_list = [opt["text"] for opt in self.options]
        
        return DBRawQuestion(
            id=UUID(int=0),  # Will be generated by database
            job_id=job_id,
            question_number=str(self.question_number),
            question_text=self.question_text,
            options=options_list,
            page_number=page_number,
            chapter_context=self.subject,
            topic_context=self.topic,
            sub_topic_context=None,
            raw_images=None,
            raw_tables=None,
            processing_status=ProcessingStatus.PENDING,
            error_message=None,
            question_id=None,
            created_at=datetime.utcnow()
        )


class UploadResponse(BaseModel):
    """Legacy upload response model for backward compatibility."""
    id: str
    status: str  # 'pending', 'processing', 'completed', 'failed'
    message: str
    uploaded_at: datetime

    @classmethod
    def from_db_extraction_job(cls, db_job: DBExtractionJob, message: str = "Upload successful") -> 'UploadResponse':
        """
        Convert database ExtractionJob to legacy UploadResponse format.
        
        Args:
            db_job: Database extraction job model
            message: Response message
        
        Returns:
            Legacy UploadResponse instance
        """
        # Map ExtractionStage to legacy status
        status_mapping = {
            ExtractionStage.QUEUED: "pending",
            ExtractionStage.VALIDATION: "processing",
            ExtractionStage.UPLOAD: "processing",
            ExtractionStage.EXTRACTION: "processing",
            ExtractionStage.COMPLETED: "completed",
            ExtractionStage.FAILED: "failed"
        }
        
        return cls(
            id=str(db_job.id),
            status=status_mapping.get(db_job.stage, "pending"),
            message=message,
            uploaded_at=db_job.created_at
        )


class UploadedTest(BaseModel):
    """Legacy uploaded test model for backward compatibility."""
    id: str
    user_id: str
    test_image_url: str
    response_image_url: Optional[str] = None
    extracted_questions: List[ExtractedQuestion]
    processing_status: str
    error_message: Optional[str] = None
    uploaded_at: datetime
    processed_at: Optional[datetime] = None
    exam_type: Optional[str] = None
    exam_date: Optional[date] = None
    exam_session: Optional[str] = None

    @classmethod
    def from_db_extraction_job(
        cls,
        db_job: DBExtractionJob,
        user_id: str,
        test_image_url: str,
        raw_questions: Optional[List[DBRawQuestion]] = None,
        response_image_url: Optional[str] = None,
        exam_type: Optional[str] = None,
        exam_date: Optional[date] = None,
        exam_session: Optional[str] = None
    ) -> 'UploadedTest':
        """
        Convert database ExtractionJob and RawQuestions to legacy UploadedTest format.
        
        Args:
            db_job: Database extraction job model
            user_id: User ID who uploaded the test
            test_image_url: URL to the uploaded test image/PDF
            raw_questions: List of database raw questions (if available)
            response_image_url: Optional URL to response sheet
            exam_type: Optional exam type
            exam_date: Optional exam date
            exam_session: Optional exam session
        
        Returns:
            Legacy UploadedTest instance
        """
        # Map ExtractionStage to legacy processing_status
        status_mapping = {
            ExtractionStage.QUEUED: "pending",
            ExtractionStage.VALIDATION: "processing",
            ExtractionStage.UPLOAD: "processing",
            ExtractionStage.EXTRACTION: "processing",
            ExtractionStage.COMPLETED: "completed",
            ExtractionStage.FAILED: "failed"
        }
        
        # Convert raw questions to legacy format
        extracted_questions = []
        if raw_questions:
            extracted_questions = [
                ExtractedQuestion.from_db_raw_question(rq)
                for rq in raw_questions
            ]
        
        return cls(
            id=str(db_job.id),
            user_id=user_id,
            test_image_url=test_image_url,
            response_image_url=response_image_url,
            extracted_questions=extracted_questions,
            processing_status=status_mapping.get(db_job.stage, "pending"),
            error_message=db_job.error,
            uploaded_at=db_job.created_at,
            processed_at=db_job.completed_at,
            exam_type=exam_type,
            exam_date=exam_date,
            exam_session=exam_session
        )


