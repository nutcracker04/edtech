def get_legacy_status_from_stage(stage: ExtractionStage) -> str:
    """
    Map ExtractionStage enum to legacy status string.
    
    Args:
        stage: ExtractionStage enum value
    
    Returns:
        Legacy status string ('pending', 'processing', 'completed', 'failed')
    """
    status_mapping = {
        ExtractionStage.QUEUED: "pending",
        ExtractionStage.VALIDATION: "processing",
        ExtractionStage.UPLOAD: "processing",
        ExtractionStage.EXTRACTION: "processing",
        ExtractionStage.COMPLETED: "completed",
        ExtractionStage.FAILED: "failed"
    }
    return status_mapping.get(stage, "pending")


def get_stage_from_legacy_status(status: str) -> ExtractionStage:
    """
    Map legacy status string to ExtractionStage enum.
    
    Args:
        status: Legacy status string
    
    Returns:
        ExtractionStage enum value
    """
    status_mapping = {
        "pending": ExtractionStage.QUEUED,
        "processing": ExtractionStage.EXTRACTION,
        "completed": ExtractionStage.COMPLETED,
        "failed": ExtractionStage.FAILED
    }
    return status_mapping.get(status, ExtractionStage.QUEUED)
