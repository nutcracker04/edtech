class UploadStatusResponse(BaseModel):
    """Legacy upload status response model for backward compatibility."""
    id: str
    status: str
    progress: int  # 0-100
    extracted_questions: Optional[List[ExtractedQuestion]] = None
    error_message: Optional[str] = None

    @classmethod
    def from_db_extraction_job(
        cls,
        db_job: DBExtractionJob,
        raw_questions: Optional[List[DBRawQuestion]] = None
    ) -> 'UploadStatusResponse':
        """
        Convert database ExtractionJob to legacy UploadStatusResponse format.
        
        Args:
            db_job: Database extraction job model
            raw_questions: Optional list of database raw questions
        
        Returns:
            Legacy UploadStatusResponse instance
        """
        # Map ExtractionStage to legacy status
        status_mapping = {
            ExtractionStage.QUEUED: "pending",
            ExtractionStage.VALIDATION: "processing",
            ExtractionStage.UPLOAD: "processing",
            ExtractionStage.EXTRACTION: "processing",
            ExtractionStage.COMPLETED: "completed",
            ExtractionStage.FAILED: "failed"
        }
        
        # Convert progress (Decimal 0-100) to int
        progress = int(db_job.progress)
        
        # Convert raw questions to legacy format if available
        extracted_questions = None
        if raw_questions and db_job.stage == ExtractionStage.COMPLETED:
            extracted_questions = [
                ExtractedQuestion.from_db_raw_question(rq)
                for rq in raw_questions
            ]
        
        return cls(
            id=str(db_job.id),
            status=status_mapping.get(db_job.stage, "pending"),
            progress=progress,
            extracted_questions=extracted_questions,
            error_message=db_job.error
        )


