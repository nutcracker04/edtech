def convert_extraction_job_to_upload_response(
    db_job: DBExtractionJob,
    message: str = "Upload successful"
) -> Dict[str, Any]:
    """
    Convert database ExtractionJob to legacy UploadResponse API format.
    
    This function ensures API backward compatibility by converting
    new database models to the format expected by existing API clients.
    
    Args:
        db_job: Database extraction job model
        message: Response message
    
    Returns:
        Dictionary in legacy API format
    """
    legacy_response = UploadResponse.from_db_extraction_job(db_job, message)
    return legacy_response.model_dump()


